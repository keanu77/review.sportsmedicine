// Run after npm run build and npm run preview -- --host 127.0.0.1 --port 4181.
import { chromium } from '@playwright/test';
import { mkdir, mkdtemp, rename } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const origin = 'http://127.0.0.1:4181';
await mkdir('docs/images', { recursive: true });
const videoDirectory = await mkdtemp(join(tmpdir(), 'review-public-demo-'));
const browser = await chromium.launch();
const errors = [];
const desktop = await browser.newContext({ viewport: { width: 1280, height: 900 }, colorScheme: 'light', reducedMotion: 'no-preference', recordVideo: { dir: videoDirectory, size: { width: 1280, height: 900 } } });
const page = await desktop.newPage();
page.on('pageerror', error => errors.push(error.message));
await page.route('https://fonts.googleapis.com/**', route => route.abort());
await Promise.all([page.waitForResponse('**/data/bibliography-index.json'), page.goto(`${origin}/?q=冰凍肩`)]);
const results = page.getByRole('region', { name: '搜尋結果', exact: true });
await results.getByRole('listitem').first().waitFor();
await page.screenshot({ path: 'docs/images/public-index.png' });
// Brief holds make the captured demonstration readable; state transitions use locator waits.
await page.waitForTimeout(3000);
await page.getByRole('searchbox').fill('frozen shoulder');
await results.getByRole('listitem').first().waitFor();
await page.waitForTimeout(3000);
await page.getByRole('combobox', { name: '篩選部位', exact: true }).selectOption('肩');
await page.waitForTimeout(3000);
await results.getByRole('button', { name: '收藏', exact: true }).first().click();
await results.getByRole('link', { name: '文獻詳情', exact: true }).first().click();
await page.getByRole('heading', { level: 1 }).waitFor();
await page.waitForTimeout(5000);
await page.getByRole('button', { name: '標記為已讀', exact: true }).click();
await page.getByRole('link', { name: '← 返回文獻索引', exact: true }).click();
await page.locator('summary').filter({ hasText: '閱讀狀態與備份' }).click();
await page.waitForTimeout(5000);
const video = page.video();
await desktop.close();
await rename(await video.path(), 'docs/images/public-workflow.webm');
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1, colorScheme: 'light', reducedMotion: 'reduce' });
const phone = await mobile.newPage();
phone.on('pageerror', error => errors.push(error.message));
await phone.route('https://fonts.googleapis.com/**', route => route.abort());
await Promise.all([phone.waitForResponse('**/data/bibliography-index.json'), phone.goto(`${origin}/?q=冰凍肩`)]);
await phone.getByRole('region', { name: '搜尋結果', exact: true }).getByRole('listitem').first().waitFor();
await phone.screenshot({ path: 'docs/images/public-mobile.png' });
