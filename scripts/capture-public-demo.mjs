const searchTop = await phone.getByRole('searchbox').evaluate(el => el.getBoundingClientRect().top);
await browser.close();
if (errors.length || !widthFits) throw new Error(JSON.stringify({ errors, widthFits }));
console.log(JSON.stringify({ desktop: '1280x900', mobile: '390x844 browser emulation', searchTop, widthFits, errors, screenshots: ['public-index.png', 'public-mobile.png'], video: 'public-workflow.webm' }));
